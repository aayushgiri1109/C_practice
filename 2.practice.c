#include <stdio.h>

int main()
{

    int radius = 5;
    int height = 6;

    printf("the area of circle with  radius %d is %f\n", radius, 3.14 * radius * radius);

    printf("the area of cylinder with radius %d and height %d is %f", radius, height, 3.14 * radius * radius * height);
 
    return 0;

}
